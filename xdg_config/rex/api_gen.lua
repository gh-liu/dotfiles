-- Generate EmmyLua definitions from Rex's machine-readable API schema.
-- Run from the dotfiles root with:
--   rex do xdg_config/rex/api_gen.lua

local function fail(message)
  error("rex api generator: " .. message, 0)
end

local function command_output(argv)
  local result, err = rex.exec(argv)
  if result == nil then
    fail(err or "command failed to start")
  end
  if not result.ok then
    fail((result.stderr or "rex api list failed") .. " (exit " .. tostring(result.code) .. ")")
  end
  return result.stdout
end

local function shell_env(name, fallback)
  local value = os.getenv(name)
  if value == nil or value == "" then
    return fallback
  end
  return value
end

local function path_join(a, b)
  if a:sub(-1) == "/" then
    return a .. b
  end
  return a .. "/" .. b
end

local function lua_string(value)
  return string.format("%q", value)
end

local function pascal(value)
  local result = {}
  for part in value:gmatch("[^%._%-]+") do
    result[#result + 1] = part:sub(1, 1):upper() .. part:sub(2)
  end
  return table.concat(result)
end

local function method_type_name(name, suffix)
  return "Rex" .. pascal(name:gsub("%.", "_")) .. suffix
end

local function is_required(schema, key)
  for _, required in ipairs(schema.required or {}) do
    if required == key then
      return true
    end
  end
  return false
end

local function enum_type(schema)
  local values = {}
  for _, value in ipairs(schema.enum or {}) do
    if type(value) == "string" then
      values[#values + 1] = lua_string(value)
    elseif type(value) == "number" or type(value) == "boolean" then
      values[#values + 1] = tostring(value)
    end
  end
  return #values > 0 and table.concat(values, "|") or nil
end

local function schema_type(schema, name, classes, emitted)
  if schema == nil then
    return "any"
  end

  local enum = enum_type(schema)
  if enum then
    return enum
  end

  if schema["$ref"] then
    return "table"
  end

  if schema.anyOf or schema.oneOf then
    local parts = {}
    for _, item in ipairs(schema.anyOf or schema.oneOf) do
      parts[#parts + 1] = schema_type(item, name, classes, emitted)
    end
    return table.concat(parts, "|")
  end

  if schema.type == "array" then
    return schema_type(schema.items, name .. "Item", classes, emitted) .. "[]"
  end

  if schema.type == "object" or schema.properties then
    local class_name = name
    if not emitted[class_name] then
      emitted[class_name] = true
      local fields = {}
      for key, property in pairs(schema.properties or {}) do
        fields[#fields + 1] = {
          key = key,
          type = schema_type(property, class_name .. pascal(key), classes, emitted),
          optional = not is_required(schema, key),
          description = property.description,
        }
      end
      table.sort(fields, function(a, b) return a.key < b.key end)
      classes[#classes + 1] = { name = class_name, fields = fields }
    end
    return class_name
  end

  if schema.type == "string" then return "string" end
  if schema.type == "integer" then return "integer" end
  if schema.type == "number" then return "number" end
  if schema.type == "boolean" then return "boolean" end
  if schema.type == "null" then return "nil" end
  return "any"
end

local json = command_output({ "rex", "api", "list", "--json" })
local document, decode_error = rex.json.decode(json)
if document == nil then
  fail(decode_error or "invalid JSON returned by rex api list")
end

local classes = {}
local emitted = {}
local methods = {}
for _, method in ipairs(document.methods or {}) do
  methods[#methods + 1] = method
  method.input_type = schema_type(
    method.input_schema,
    method_type_name(method.name, "Args"),
    classes,
    emitted
  )
  method.output_type = schema_type(
    method.output_schema,
    method_type_name(method.name, "Result"),
    classes,
    emitted
  )
end

table.sort(classes, function(a, b) return a.name < b.name end)
table.sort(methods, function(a, b) return a.name < b.name end)

local lines = {
  "---@meta",
  "",
  "-- Generated by xdg_config/rex/api_gen.lua.",
  "-- Do not edit this file directly; run the generator again after Rex updates.",
  "",
}

for _, class in ipairs(classes) do
  lines[#lines + 1] = "---@class " .. class.name
  for _, field in ipairs(class.fields) do
    local optional = field.optional and "?" or ""
    lines[#lines + 1] = "---@field " .. field.key .. optional .. " " .. field.type
  end
  lines[#lines + 1] = ""
end

local groups = {}
for _, method in ipairs(methods) do
  local group, member = method.name:match("^([^.]+)%.(.+)$")
  if group and member then
    groups[group] = groups[group] or {}
    groups[group][#groups[group] + 1] = {
      member = member,
      input_type = method.input_type,
      output_type = method.output_type,
      description = method.description,
    }
  end
end

for group, group_methods in pairs(groups) do
  local class_name = "Rex" .. pascal(group)
  lines[#lines + 1] = "---@class " .. class_name
  table.sort(group_methods, function(a, b) return a.member < b.member end)
  for _, method in ipairs(group_methods) do
    lines[#lines + 1] = "---@field " .. method.member
      .. " fun(args: " .. method.input_type .. "): " .. method.output_type .. ", string?"
  end
  lines[#lines + 1] = ""
end

lines[#lines + 1] = "---@class RexContext"
lines[#lines + 1] = "---@field session_id string"
lines[#lines + 1] = "---@field block_id string?"
lines[#lines + 1] = "---@field client_id string?"
lines[#lines + 1] = ""
lines[#lines + 1] = "---@class RexRuntime"
lines[#lines + 1] = "---@field session RexSession"
lines[#lines + 1] = "---@field block RexBlock"
lines[#lines + 1] = "---@field client RexClient"
lines[#lines + 1] = "---@field bind fun(key: string, action: string|fun(ctx: RexContext, ev: table), args: table?)"
lines[#lines + 1] = "---@field unbind fun(key: string, target: string|function|nil): integer"
lines[#lines + 1] = "---@field action fun(definition: table)"
lines[#lines + 1] = "---@field mode fun(name: string, options: { exclusive: boolean }?)"
lines[#lines + 1] = "---@field call fun(method: string, args: table?): table, string?"
lines[#lines + 1] = "---@field json table"
lines[#lines + 1] = ""
lines[#lines + 1] = "---@type RexRuntime"
lines[#lines + 1] = "rex = rex"

local xdg = shell_env("XDG_CONFIG_HOME", path_join(shell_env("HOME", "."), ".config"))
local output_path = path_join(path_join(xdg, "rex"), "api.lua")
local file, open_error = io.open(output_path, "w")
if not file then
  fail("cannot write " .. output_path .. ": " .. tostring(open_error))
end
file:write(table.concat(lines, "\n"), "\n")
file:close()

print("Generated " .. output_path .. " from " .. tostring(#methods) .. " Rex API methods")
